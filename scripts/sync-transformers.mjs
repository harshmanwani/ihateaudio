/**
 * Copies transformers.js into public/ as a plain static file.
 *
 * This is not tidiness, it is the fix for a bug that cost two sessions.
 *
 * Importing `@huggingface/transformers` from application code lets Vite pre-bundle
 * it with esbuild. The library then spawns its own worker, and that worker
 * references module ids belonging to the main bundle which do not exist in worker
 * scope. What surfaces is a missing method deep inside the bundle — `ke._b is not
 * a function`, with the property name changing every time the pre-bundle is
 * rebuilt, which is the tell that the identifier is generated rather than ours.
 * Nothing about the message points at bundling.
 *
 * Served from public/ and imported by absolute URL, the library is never bundled,
 * its worker resolves against real files, and the problem does not arise. The same
 * approach is what the CapCut GPT codebase settled on after hitting the identical
 * failure under Turbopack, which is where this fix came from.
 *
 * The path carries the version so it can be cached immutably and an upgrade
 * invalidates itself.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let packageDir;
let version;
try {
  packageDir = join(root, 'node_modules', '@huggingface', 'transformers');
  version = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8')).version;
} catch {
  console.warn(
    '[transformers] not installed — skipping. Transcription will be unavailable ' +
      'until you run npm install.'
  );
  process.exit(0);
}

/**
 * The library, plus the ONNX Runtime build it insists on.
 *
 * `transformers.min.js` is the only dist here a browser can load directly.
 * `transformers.web.min.js` looks like the browser one and is not: it carries a
 * bare `onnxruntime-web/webgpu` import for a bundler to resolve, and loading it by
 * URL fails on the module specifier before anything else happens.
 *
 * That build has ONNX Runtime compiled in with WebGPU support, and it resolves its
 * WebAssembly to the asyncify variant unconditionally — asking for the plain build
 * by pointing wasmPaths at a directory holding only that one just 404s. So the
 * asyncify pair is what has to be here, and it comes from onnxruntime-web rather
 * than from this package, which ships no .wasm at all.
 *
 * It is 23.1 MB against the 10.5 MB a v2 visitor fetched, and it buys roughly twice
 * the transcription speed — measured at 4.0 s versus 2.1 s on thirty seconds of
 * audio. The runtime is cached on a versioned path and the model is four times its
 * size, so the extra megabytes are paid once and repaid on the first clip.
 */
const FILES = ['transformers.min.js'];
const ORT_FILES = ['ort-wasm-simd-threaded.asyncify.mjs', 'ort-wasm-simd-threaded.asyncify.wasm'];

const ortDir = join(root, 'node_modules', 'onnxruntime-web', 'dist');
const target = join(root, 'public', 'lib', 'transformers', version);
mkdirSync(target, { recursive: true });

let copied = 0;
let bytes = 0;
for (const file of [...FILES, ...ORT_FILES]) {
  const from = FILES.includes(file) ? join(packageDir, 'dist', file) : join(ortDir, file);
  if (!existsSync(from)) {
    console.error(`[transformers] missing ${from}`);
    process.exit(1);
  }
  const to = join(target, file);
  if (!existsSync(to) || statSync(to).size !== statSync(from).size) {
    copyFileSync(from, to);
    copied += 1;
  }
  bytes += statSync(to).size;
}

const generated = `/**
 * Generated by scripts/sync-transformers.mjs. Do not edit.
 *
 * The installed transformers.js version, which is also the path segment its
 * browser build is served under so it can be cached immutably.
 *
 * It is served as a static file and imported by URL rather than bundled — see the
 * script for the bug that forces this.
 */
export const TRANSFORMERS_VERSION = '${version}';
`;
const versionFile = join(root, 'src', 'lib', 'ai', 'transformers-version.ts');
if (!existsSync(versionFile) || readFileSync(versionFile, 'utf8') !== generated) {
  writeFileSync(versionFile, generated);
}

console.log(
  `[transformers] ${version} in public/lib/transformers/${version}/ ` +
    `(${copied} of ${FILES.length + ORT_FILES.length} copied, ` +
    `${(bytes / 1048576).toFixed(1)} MB total)`
);
